"""Phase 5: PDF reports."""
import io

import simulator
from tests.conftest import AUTH, make_alert, make_observation, start_session


def _pdf_text(content: bytes) -> str:
    """Pull the text out of the PDF so we can check the sections exist."""
    from pypdf import PdfReader
    return "\n".join(page.extract_text() for page in PdfReader(io.BytesIO(content)).pages)


def test_report_requires_key(client):
    sid = start_session(client)
    assert client.post(f"/sessions/{sid}/report").status_code == 401
    assert client.get("/reports/1/download").status_code == 401


def test_build_and_download_report_with_all_sections(client):
    client.headers.update(AUTH)
    sid = simulator.run(client, duration=30, interval=0, seed=7, quiet=True)
    # add one potential_risk + one not_observable alert so every section has content
    sid2 = start_session(client)
    alerts = [make_alert("low", "potential_risk"), make_alert("low", "not_observable")]
    client.post("/observations", json=make_observation(sid2, alerts=alerts), headers=AUTH)

    for session_id in (sid, sid2):
        r = client.post(f"/sessions/{session_id}/report")
        assert r.status_code == 201, r.text
        rep = r.json()
        assert rep["download_url"] == f"/reports/{rep['id']}/download" and rep["is_mock"] is True

        pdf = client.get(rep["download_url"])
        assert pdf.status_code == 200
        assert pdf.headers["content-type"] == "application/pdf"
        assert pdf.content.startswith(b"%PDF")

        text = _pdf_text(pdf.content)
        for section in ["1. Observed facts", "2. Inferred", "3. Potential risks",
                        "4. Cannot be observed", "5. AI explanation", "SIMULATED TEST DATA"]:
            assert section in text, f"missing section: {section}"
        assert "malware" not in text.lower()

    assert len(client.get(f"/sessions/{sid}/reports").json()) == 1


def test_unicode_and_markdown_in_insight_do_not_break_pdf(client, monkeypatch):
    from app import config
    from app.services import insights
    monkeypatch.setattr(config, "GEMINI_API_KEY", "fake")
    monkeypatch.setattr(insights, "_call_gemini",
                        lambda ev: "## What was observed\n* “Smart quotes” — dash ≈ 9.8 MB → tracker • 日本語 ✓")
    sid = start_session(client)
    client.post("/observations", json=make_observation(sid, alerts=[make_alert()]), headers=AUTH)
    rep = client.post(f"/sessions/{sid}/report", headers=AUTH).json()
    text = _pdf_text(client.get(rep["download_url"], headers=AUTH).content)
    assert "Generated by Gemini" in text and "Smart quotes" in text


